import numpy as np

np.random.seed(42)

X = np.array([
    [0, 0],
    [0, 1],
    [1, 0],
    [1, 1]
])

y = np.array([[0], [1], [1], [0]])

def sigmoid(x):
    return 1 / (1 + np.exp(-x))

W1 = np.random.randn(2, 4)
b1 = np.zeros((1, 4))
W2 = np.random.randn(4, 1)
b2 = np.zeros((1, 1))

lr = 0.5
epochs = 10000

for epoch in range(epochs):
    hidden = sigmoid(X @ W1 + b1)
    output = sigmoid(hidden @ W2 + b2)

    error = output - y

    d_output = error * output * (1 - output)
    d_hidden = (d_output @ W2.T) * hidden * (1 - hidden)

    W2 -= lr * (hidden.T @ d_output) / len(X)
    b2 -= lr * np.mean(d_output, axis=0, keepdims=True)
    W1 -= lr * (X.T @ d_hidden) / len(X)
    b1 -= lr * np.mean(d_hidden, axis=0, keepdims=True)

print("Testing the trained ANN:")
predictions = sigmoid(sigmoid(X @ W1 + b1) @ W2 + b2)

for i in range(len(X)):
    result = 1 if predictions[i, 0] >= 0.5 else 0
    print(X[i], "Predicted:", result, "Actual:", y[i, 0])