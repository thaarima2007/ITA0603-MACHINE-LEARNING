import pandas as pd
from itertools import product

df = pd.read_csv('training_data.csv')

X = df.iloc[:, :-1].values.tolist()
Y = df.iloc[:, -1].tolist()

n = len(X[0])
domains = [set(row[i] for row in X) for i in range(n)]

S = ['Ø'] * n
G = {tuple(['?'] * n)}

def covers(h, x):
    return all(a == '?' or a == b for a, b in zip(h, x))

def more_general(h1, h2):
    return all(b == 'Ø' or a == '?' or a == b
               for a, b in zip(h1, h2))

for x, label in zip(X, Y):
    if label == 'Yes':
        G = {g for g in G if covers(g, x)}

        for i in range(n):
            if S[i] == 'Ø':
                S[i] = x[i]
            elif S[i] != x[i]:
                S[i] = '?'

        G = {g for g in G if more_general(g, S)}

    else:
        new_G = set()

        for g in G:
            if not covers(g, x):
                new_G.add(g)
            else:
                for i in range(n):
                    if g[i] == '?':
                        for value in domains[i]:
                            if value != x[i]:
                                h = list(g)
                                h[i] = value

                                if more_general(h, S):
                                    new_G.add(tuple(h))

        G = {
            g for g in new_G
            if not any(
                g != other and more_general(other, g)
                for other in new_G
            )
        }

    print("S =", S)
    print("G =", G)
    print()

print("Final Specific Boundary S:", S)
print("Final General Boundary G:", G)