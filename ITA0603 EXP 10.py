import numpy as np
from sklearn.mixture import GaussianMixture

X = np.array([
    [1.0], [1.5], [2.0], [2.5], [8.0],
    [8.5], [9.0], [9.5]
])

model = GaussianMixture(
    n_components=2, random_state=42, n_init=5
)

model.fit(X)

labels = model.predict(X)

print("Cluster Assignments:", labels)
print("Cluster Means:")
print(model.means_)
print("Log Likelihood:", model.score(X) * len(X))